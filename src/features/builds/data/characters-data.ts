export type Element =
  | "anemo"
  | "cryo"
  | "dendro"
  | "electro"
  | "geo"
  | "hydro"
  | "pyro";

export type WeaponType =
  | "bow"
  | "catalyst"
  | "claymore"
  | "polearm"
  | "sword";

/** Recommended main stats shown in the "RECOMMENDED STATS" 2x2 grid. */
export interface RecommendedStats {
  /** First cell, e.g. "CRIT DMG: 200%+". */
  mastery: string;
  /** Second cell, e.g. "CRIT RATE: 70%". */
  critRate: string;
  /** Third cell, e.g. "ATK: 2000+". */
  critDmg: string;
  /** Fourth cell, e.g. "ER: 120". */
  er: string;
}

export interface CharacterBuildData {
  slug: string;
  name: string;
  /** Rarity as a string, e.g. "5" or "4" (editable per character). */
  rarity: string;
  element: Element;
  weaponType: WeaponType;
  /** Keys of 1 or 2 artifact sets from `artifacts-data.ts`. */
  artifact: string[];
  /** Text under the Sands artifact icon (stat offered by that piece). */
  sandStat: string;
  /** Text under the Goblet artifact icon (stat offered by that piece). */
  gobletStat: string;
  /** Text under the Circlet artifact icon (stat offered by that piece). */
  circletStat: string;
  /** Text under the "PRIORITY STATS" heading. */
  priorityStats: string;
  /** Cells for the "RECOMMENDED STATS" 2x2 grid. */
  recommendedStats: RecommendedStats;
  /** Editable level shown next to the "Normal attack" talent. */
  normalAttackLevel: string;
  /** Editable level shown next to the "Elemental Skill" talent. */
  elementalSkillLevel: string;
  /** Editable level shown next to the "Ultimate" talent. */
  ultimateLevel: string;
  /** `true` shows the full build; `false` shows a "Coming soon" placeholder. */
  available: boolean;
  /** Names (keys) of the 5 recommended weapons from `weapons-data.ts`. */
  weapons: string[];
}

